def explain_text(text):
    """给一段文字匹配知识库，返回原因列表"""
    if not text:
        return []
    reasons = []
    for item in KNOWLEDGE:
        if any(k in text for k in item["match"]):
            if item["why"] not in reasons:
                reasons.append(item["why"])
    return reasons


def attach_reasons(organized):
    """把原因附加到步骤和食材上"""
    steps = []
    for s in organized.get("steps", []):
        if isinstance(s, dict):
            text = s.get("text", "")
            why = s.get("why", [])
        else:
            text = s
            why = []
        for r in explain_text(text):
            if r not in why:
                why.append(r)
        steps.append({"text": text, "why": why})
    organized["steps"] = steps

    for cat in ("主料", "配料", "调料", "主食"):
        for it in organized.get("ingredients", {}).get(cat, []):
            why = explain_text(it.get("name", ""))
            it["why"] = why
    return organized
